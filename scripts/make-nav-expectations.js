// Writes test/fixtures/nav-expected.json: drives replayed through the
// JavaScript navigator and voice (web/js/nav.js, web/js/voice.js), with what
// they report and speak at every fix. The Java copies used by the Android
// location service replay the same file in their unit tests and must give the
// same answers, so the two copies cannot drift apart unnoticed.
//
// Run after any change to nav.js or voice.js, then run the Java tests:
//   node scripts/make-nav-expectations.js
//   npm run android:test
// test/nav-expected.test.js fails while the file is out of date.

const fs = require('fs');
const path = require('path');
const { createNavigator, distanceM, distanceToRouteM } = require('../web/js/nav');
const { createVoice } = require('../web/js/voice');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'test', 'fixtures', 'nav-expected.json');
const METRES_PER_DEG_LAT = 111195;

// Fixes along the route line every spacingM metres, ending on the last point.
function along(route, spacingM) {
  const g = route.geometry;
  const fixes = [];
  let done = 0;
  let next = 0;
  for (let i = 0; i < g.length - 1; i += 1) {
    const a = { lat: g[i][0], lng: g[i][1] };
    const b = { lat: g[i + 1][0], lng: g[i + 1][1] };
    const seg = distanceM(a, b);
    while (next <= done + seg) {
      const t = seg === 0 ? 0 : (next - done) / seg;
      fixes.push({ lat: a.lat + (b.lat - a.lat) * t, lng: a.lng + (b.lng - a.lng) * t });
      next += spacingM;
    }
    done += seg;
  }
  const end = g[g.length - 1];
  fixes.push({ lat: end[0], lng: end[1] });
  return fixes;
}

function north(p, metres) {
  return { lat: p.lat + metres / METRES_PER_DEG_LAT, lng: p.lng };
}

// A point north of p whose distance to the route line itself is targetM.
// Moving north by targetM is not enough where the road bends.
function offLine(route, p, targetM) {
  let k = 0;
  while (distanceToRouteM(north(p, k), route.geometry) < targetM) k += 0.5;
  return north(p, k);
}

function scenarios(route) {
  const start = { lat: route.geometry[0][0], lng: route.geometry[0][1] };
  const drive50 = along(route, 50);
  const offRoadStart = [];
  for (let i = 0; i < 12; i += 1) offRoadStart.push(north(start, 80 + (i % 2 ? 15 : -15)));
  for (const d of [140, 160, 180, 200]) offRoadStart.push(north(start, d));
  const leaving = drive50.slice(0, 12);
  for (let i = 0; i < 4; i += 1) leaving.push(north(drive50[12], 100 + i * 20));
  // Either side of the 40 m off-route limit, measured from the nearest segment.
  const edge = drive50.slice(0, 40);
  for (let i = 0; i < 3; i += 1) edge.push(offLine(route, drive50[40], 35));
  for (let i = 0; i < 3; i += 1) edge.push(offLine(route, drive50[40], 45));
  return [
    { name: 'whole route, a fix every 50 m', fixes: drive50 },
    { name: 'whole route, a fix every 300 m (GPS gaps)', fixes: along(route, 300) },
    { name: 'waiting 80 m off the road, then driving away', fixes: offRoadStart },
    { name: 'joining the route, then leaving it', fixes: leaving },
    { name: 'drifting 35 m off the line, then 45 m', fixes: edge },
  ];
}

// Rounded so the file stays readable; the Java test compares with a tolerance.
const round = (x, dp) => (Number.isFinite(x) ? Number(x.toFixed(dp)) : x);

function build() {
  const route = JSON.parse(fs.readFileSync(path.join(ROOT, 'test', 'fixtures', 'route-perth-fremantle.json'), 'utf8')).route;
  return {
    description: 'Generated by scripts/make-nav-expectations.js from web/js/nav.js and web/js/voice.js. Do not edit by hand.',
    route: 'route-perth-fremantle.json',
    scenarios: scenarios(route).map((sc) => {
      const nav = createNavigator(route);
      let spokenText = null;
      const voice = createVoice({ speak: (t) => { spokenText = t; } });
      const fixes = sc.fixes.map((f) => ({ lat: round(f.lat, 8), lng: round(f.lng, 8) }));
      const expected = fixes.map((f) => {
        const s = nav.update(f);
        spokenText = null;
        voice.onUpdate(s);
        return {
          stepIndex: s.stepIndex,
          distanceToNextM: round(s.distanceToNextM, 3),
          remainingM: round(s.remainingM, 3),
          remainingS: round(s.remainingS, 3),
          offRoute: s.offRoute,
          arrived: s.arrived,
          spoken: spokenText,
        };
      });
      return { name: sc.name, fixes, expected };
    }),
  };
}

if (require.main === module) {
  fs.writeFileSync(OUT, JSON.stringify(build(), null, 1) + '\n');
  console.log('wrote ' + path.relative(ROOT, OUT));
}

module.exports = { build };
